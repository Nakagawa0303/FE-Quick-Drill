def original(year, subject, kind):
    return next(x for x in MANIFEST if x['year'] == year and f'_kamoku_{subject.lower()}_{kind}.' in x['local'])

def raw_text(year, subject):
    s = (TMP/original(year, subject, 'qs')['local']).with_suffix('.txt').read_text(encoding='utf-8')
    s = re.sub(r'=== PAGE \d+ ===', '', s)
    s = re.sub(r'－\s*\d+\s*－', '', s)
    # 原本に付された読み仮名だけを除去する。
    s = re.sub(r'^\s*(たい|ぜい)\s*$', '', s, flags=re.M)
    return s

def sections(year, subject):
    s = raw_text(year, subject)
    matches = list(re.finditer(r'^問([０-９0-9]+)\s+', s, re.M))
    result = {}
    for i, m in enumerate(matches):
        body = s[m.end(): matches[i+1].start() if i+1 < len(matches) else len(s)]
        body = body.split('〔 メ モ 用 紙 〕')[0].split('試験問題に記載されている会社名')[0]
        result[int(unicodedata.normalize('NFKC', m[1]))] = body.strip()
    return result

def compact(s):
    return ''.join(line.strip() for line in s.splitlines() if line.strip())

def answers(year, subject):
    s = (TMP/original(year, subject, 'ans')['local']).with_suffix('.txt').read_text(encoding='utf-8')
    return {int(n): label for n, label in re.findall(r'問\s*([0-9]+)\s+([アイウエオカキクケコ])', s)}

